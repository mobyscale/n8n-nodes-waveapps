// Downloads the Wave public GraphQL schema with an introspection query and writes:
//   schema/wave.graphql             the schema in SDL form (input for graphql-codegen)
//   nodes/Wave/generated/enums.ts   the enum values with descriptions, for node dropdowns
// Reads WAVE_ACCESS_TOKEN from the environment or from the uncommitted .env file.
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { loadEnvFile } from 'node:process';
import { fileURLToPath } from 'node:url';
import { buildClientSchema, getIntrospectionQuery, printSchema } from 'graphql';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env');
if (existsSync(envPath)) loadEnvFile(envPath);

const token = process.env.WAVE_ACCESS_TOKEN;
if (!token) {
	console.error('Set WAVE_ACCESS_TOKEN in .env or in the environment.');
	process.exit(1);
}

const response = await fetch('https://gql.waveapps.com/graphql/public', {
	method: 'POST',
	headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
	body: JSON.stringify({ query: getIntrospectionQuery({ descriptions: true }) }),
});
const result = await response.json();
if (result.errors?.length) {
	console.error(JSON.stringify(result.errors, null, 2));
	process.exit(1);
}

const write = (path, content) => {
	const target = resolve(root, path);
	mkdirSync(dirname(target), { recursive: true });
	writeFileSync(target, content);
	console.log(`Wrote ${path}`);
};

const sdl = `${printSchema(buildClientSchema(result.data))}\n`;
write('schema/wave.graphql', sdl);
console.log(`Schema SHA-256: ${createHash('sha256').update(sdl).digest('hex')}`);
console.log('Compare it with the baseline in docs/wave-api.md.');

const enums = result.data.__schema.types
	.filter((type) => type.kind === 'ENUM' && !type.name.startsWith('__'))
	.sort((a, b) => a.name.localeCompare(b.name));

const lines = [
	'// Generated by scripts/introspect.mjs. Do not edit by hand. Run `npm run schema:update`.',
	'',
	'export interface WaveEnumValue {',
	'\tvalue: string;',
	'\tdescription?: string;',
	'\tdeprecated?: boolean;',
	'}',
	'',
	'export const WAVE_ENUMS = {',
];
for (const type of enums) {
	lines.push(`\t${type.name}: [`);
	for (const value of type.enumValues) {
		const entry = { value: value.name };
		if (value.description) entry.description = value.description.trim();
		if (value.isDeprecated) entry.deprecated = true;
		lines.push(`\t\t${JSON.stringify(entry)},`);
	}
	lines.push('\t],');
}
lines.push('} satisfies Record<string, WaveEnumValue[]>;', '');
write('nodes/Wave/generated/enums.ts', lines.join('\n'));
